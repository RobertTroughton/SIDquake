#!/usr/bin/env node
/**
 * build-random-pool.js - pre-filter the HVSC index down to the Random SID pool.
 *
 * The Random SID button only ever picks a path from the curated composer folders
 * listed in public/hvsc-random.json. Resolving that in the browser meant fetching
 * the whole 12 MB public/hvsc-index.json (~2 MB gzipped) and filtering it, which
 * is the most expensive thing on the landing page for the cheapest possible
 * answer. This writes the filtered path list out at build time instead, ~40x
 * smaller, so the front door costs a small fetch rather than the whole index.
 *
 * Usage:
 *   node scripts/build-random-pool.js
 *
 * Output: public/hvsc-random-pool.json (generated - do not edit by hand).
 * hvsc-random.js still falls back to the full index if this file is missing, so
 * a deploy that skips this step degrades to the old behaviour rather than
 * breaking.
 */

const fs = require('fs');
const path = require('path');

const PUBLIC = path.join(__dirname, '..', 'public');
const INDEX = path.join(PUBLIC, 'hvsc-index.json');
const CURATED = path.join(PUBLIC, 'hvsc-random.json');
const OUT = path.join(PUBLIC, 'hvsc-random-pool.json');

function main() {
    for (const [label, p] of [['HVSC index', INDEX], ['curated path list', CURATED]]) {
        if (!fs.existsSync(p)) {
            console.error(`Missing ${label}: ${p}`);
            process.exit(1);
        }
    }

    const index = JSON.parse(fs.readFileSync(INDEX, 'utf8'));
    const curated = JSON.parse(fs.readFileSync(CURATED, 'utf8'));
    const entries = index.entries || [];

    // Match hvsc-random.js: a prefix selects a folder, so it is compared with a
    // trailing slash rather than as a bare string prefix (otherwise
    // ".../Hubbard_Rob" would also match ".../Hubbard_Robert").
    const prefixes = (curated.paths || []).map((p) => (p.endsWith('/') ? p : p + '/'));
    if (!prefixes.length) {
        console.error(`${CURATED} lists no paths - nothing to filter with.`);
        process.exit(1);
    }

    const paths = entries
        .map((e) => e.p)
        .filter((p) => typeof p === 'string' && prefixes.some((pre) => p.startsWith(pre)));

    if (!paths.length) {
        console.error('No tunes matched the curated prefixes - refusing to write an empty pool.');
        process.exit(1);
    }

    // Sorted so the output is stable across index rebuilds that reorder entries.
    paths.sort();

    const out = {
        description: 'Generated by scripts/build-random-pool.js - do not edit by hand',
        hvsc: index.hvsc || null,
        generated: index.generated || null,
        count: paths.length,
        paths,
    };
    fs.writeFileSync(OUT, JSON.stringify(out));

    const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
    const indexKb = (fs.statSync(INDEX).size / 1024).toFixed(1);
    console.error(`Random pool: ${paths.length} tunes from ${prefixes.length} folders `
        + `(${kb} KB, vs ${indexKb} KB for the full index).`);
}

main();
